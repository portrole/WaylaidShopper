#!/usr/bin/env python3
"""Generate ../CrateData.lua from ForeverDiff's Waylaid Crates page.

Source: https://foreverdiff.com/waylaid-crates/  (read from the WoW Forever client, build 1.60.1.71091,
synced 2026-11-25). Save that page as HTML to regenerate (the saved copy is not part of the repository).
Cross-checks: zockify.com/forever/waylaid-crates (same 30 crates and counts), and every material item ID was
checked against the item names in QuestieDB 1.1.6 (Forever build, commit 4377c981ac). Two materials have no link on
ForeverDiff (name shared by several items); their IDs come from that QuestieDB check (FIX_IDS below).
Rewards (Merchant's Favor per sealed crate) are server-side: Apprentice/Journeyman/Expert values are the
community-reported ones (zockify, games.gg); Artisan is an ESTIMATE (marked est = true in the data).

Usage:  python3 parse_foreverdiff.py <saved foreverdiff page>.html > crates.json
        python3 gen_cratedata.py crates.json
"""
import json, sys, os, datetime
FIX_IDS = {'Gold Power Core': 10558, 'Dark Iron Ore': 11370}
TIER = {10: None}
FAVOR = {  # tier -> (common, uncommon, estimated?)
    'Apprentice': (5, 10, False), 'Journeyman': (10, 20, False), 'Expert': (15, 30, False), 'Artisan': (20, 40, True)}
PROF = {'Herbs': 'Herbalism', 'Ore': 'Mining', 'Ingots': 'Mining', 'Textiles': 'Tailoring/Leatherworking',
        'Fabrics': 'Tailoring/Leatherworking', 'Curiosities': 'Enchanting', 'Parts': 'Engineering'}
TIER_ORDER = ['Apprentice', 'Journeyman', 'Expert', 'Artisan']
def tier_of(name):
    for t in TIER_ORDER:
        if t in name: return t
    raise SystemExit('no tier in ' + name)
def lua_str(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
crates = json.load(open(sys.argv[1] if len(sys.argv) > 1 else 'crates.json'))
assert len(crates) == 30, len(crates)
crates.sort(key=lambda c: (TIER_ORDER.index(tier_of(c['name'])), c['category'], c['name']))
out = ['-- WaylaidShopper CrateData: GENERATED by tools/gen_cratedata.py, do not edit by hand.',
       '-- Source: foreverdiff.com/waylaid-crates (WoW Forever client build 1.60.1.71091, synced 2026-11-25);',
       '-- material IDs cross-checked against QuestieDB 1.1.6 Forever item names. Favor: community reports (Artisan = estimate).',
       '-- C[i] = { id, name, tier, category, level, quality (1 common / 2 uncommon), favor, favorEstimated, profession,',
       '--          bundles = { {itemID, count, name}, ... } }   -- ONE bundle fills the crate',
       'local ADDON, WS = ...', 'WS = WS or {}', 'local C = {']
mats = {}
for c in crates:
    t = tier_of(c['name']); q = 2 if (c['quality'] or '').lower() == 'uncommon' else 1
    fav = FAVOR[t]; favor = fav[q - 1]
    bs = []
    for b in c['bundles']:
        iid = b['item'] or FIX_IDS.get(b['name'])
        if not iid: raise SystemExit('missing id for ' + b['name'])
        mats[iid] = b['name']
        bs.append('{%d,%d,%s}' % (iid, b['count'], lua_str(b['name'])))
    out.append('{%d,%s,%s,%s,%d,%d,%d,%s,%s,{%s}},' % (c['id'], lua_str(c['name']), lua_str(t), lua_str(c['category']),
        c['level'], q, favor, 'true' if fav[2] else 'false', lua_str(PROF.get(c['category'], '?')), ','.join(bs)))
out.append('}')
out.append('local list = {}')
out.append('for i, r in ipairs(C) do')
out.append('    local b = {}')
out.append('    for j, x in ipairs(r[10]) do b[j] = { item = x[1], count = x[2], name = x[3] } end')
out.append('    list[i] = { id = r[1], name = r[2], tier = r[3], category = r[4], level = r[5], quality = r[6], favor = r[7],')
out.append('                favorEstimated = r[8], profession = r[9], bundles = b }')
out.append('end')
out.append('WS.Crates = list')
out.append('WS.TIERS = { "Apprentice", "Journeyman", "Expert", "Artisan" }')
out.append('WS.CATEGORIES = { "Herbs", "Ore", "Ingots", "Textiles", "Fabrics", "Curiosities", "Parts" }')
out.append('WS.SEALED = { 248765, 248766, 248767, 248768, 248769, 248770, 248771, 248772, 248773, 248774, 248775, 248776, 248777, 248778, 248779 }')
out.append('WS.DATA_SOURCE = "foreverdiff.com/waylaid-crates, client 1.60.1.71091 (2026-11-25)"')
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'CrateData.lua')
open(dst, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('crates', len(crates), 'materials', len(mats))
